"""LangGraph nodes for deterministic claim deconstruction and evidence review.

The evaluator in this module is deliberately conservative and deterministic.
Its results are screening aids, not legal conclusions or a substitute for
professional patent analysis. Evidence quotes are selected only from stored
retrieval text and are never generated by a language model.
"""

from __future__ import annotations

import hashlib
import logging
import math
import re
from collections.abc import Iterable
from typing import Any
from uuid import NAMESPACE_URL, uuid5

from ai_engine.state import (
    AnalysisState,
    EvidenceItem,
    LimitationAssessmentResult,
    LimitationObject,
)

logger = logging.getLogger(__name__)

_WHITESPACE_RE = re.compile(r"\s+")
_LEADING_CLAIM_NUMBER_RE = re.compile(
    r"^\s*(?:(?:claim\s+)?\d{1,4}\s*[.) :]\s+)",
    flags=re.IGNORECASE,
)
_SPLIT_LIMITATION_RE = re.compile(
    r";\s*|(?=\([a-z]\)\s+)|(?=\([ivx]+\)\s+)"
    r"|(?=\bwherein\b)|(?=\bwhereby\b)|(?=\bsuch that\b)",
    flags=re.IGNORECASE,
)
_LIST_ITEM_BOUNDARY_RE = re.compile(
    r",\s*(?=(?:and\s+|or\s+)?"
    r"(?:a|an|the|at least one|one or more|a plurality of)\b)",
    flags=re.IGNORECASE,
)
_LEADING_CONJUNCTION_RE = re.compile(r"^(?:and|or)\s+", flags=re.IGNORECASE)
_TOKEN_RE = re.compile(r"[a-z0-9]+", flags=re.IGNORECASE)
_SENTENCE_RE = re.compile(r"[^.!?;\n]+[.!?;]?", flags=re.MULTILINE)
_NEGATION_RE = re.compile(
    r"\b(?:does not|do not|did not|without|lacks?|lack of|absence of|"
    r"free of|fails? to|not including|not contain)\b",
    flags=re.IGNORECASE,
)

# These are function words and common patent boilerplate, not a domain model.
_STOPWORDS = frozenset(
    "a an the and or of to in on at by for from with without via as is are was "
    "were be being been comprises comprise comprising includes include including "
    "wherein whereby such that said claimed claim claims according configured "
    "adapted arranged associated coupled connected based using use used first "
    "second third one more plurality at least thereof thereon thereof".split()
)


def deconstruct_claim_node(state: AnalysisState) -> dict[str, Any]:
    """Split the target claim into ordered limitation records.

    A deterministic parser is used so the extracted limitation text remains
    traceable to the supplied claim. It recognizes semicolon/lettered lists,
    ``wherein`` clauses, and conservative comma-separated component lists.
    When no reliable boundary is found, the entire claim remains one limitation
    rather than inventing a decomposition.
    """
    claim_text = _normalize_text(state.get("claim_text", ""))
    if not claim_text:
        return {
            "limitations": [],
            "status": "FAILED",
            "error_message": "Claim text is empty; deconstruction was not run.",
        }

    try:
        limitation_texts = _split_claim_into_limitations(claim_text)
        if not limitation_texts:
            raise ValueError("No non-empty technical limitations were extracted.")

        analysis_id = state.get("analysis_id", "")
        limitations: list[dict[str, Any]] = []
        for index, limitation_text in enumerate(limitation_texts, start=1):
            limitation_id = str(
                uuid5(
                    NAMESPACE_URL,
                    f"patentshield:{analysis_id}:limitation:{index}",
                )
            )
            limitation = LimitationObject(
                limitation_id=limitation_id,
                limitation_index=index,
                text=limitation_text,
                evidence_requirement=(
                    "Find prior-art passages that explicitly disclose or are "
                    f"materially related to this limitation: {limitation_text}"
                ),
            )
            limitations.append(limitation.model_dump(mode="json"))

        return {
            "limitations": limitations,
            "status": "DECONSTRUCTED",
            "error_message": None,
        }
    except Exception as exc:
        # Never log claim text or exception strings that may echo user content.
        logger.error(
            "Claim deconstruction failed for analysis_id=%s error_type=%s.",
            state.get("analysis_id", "unknown"),
            type(exc).__name__,
        )
        return {
            "limitations": [],
            "status": "FAILED",
            "error_message": "Claim deconstruction failed. Check the application logs.",
        }


def hybrid_retrieval_node(state: AnalysisState) -> dict[str, Any]:
    """Retrieve tenant-scoped evidence for each extracted limitation.

    Failures for individual limitations are recorded without logging the claim
    text or evidence content. If some searches fail, successful evidence is
    retained and the state receives a warning status.
    """
    limitations = state.get("limitations", [])
    tenant_id = state.get("tenant_id", "")
    if not tenant_id:
        return {
            "retrieved_evidence": [],
            "status": "FAILED",
            "error_message": "Tenant context is missing; retrieval was not run.",
        }
    if not limitations:
        return {
            "retrieved_evidence": [],
            "status": "FAILED",
            "error_message": state.get("error_message")
            or "No limitations are available for retrieval.",
        }

    try:
        from django.conf import settings

        from retrieval.services import retrieve_evidence

        top_n = int(
            getattr(settings, "PATENTSHIELD_LIMITATION_RETRIEVAL_TOP_N", 5)
        )
        if top_n < 1:
            raise ValueError(
                "PATENTSHIELD_LIMITATION_RETRIEVAL_TOP_N must be positive."
            )
    except Exception as exc:
        logger.error(
            "Retrieval initialization failed for analysis_id=%s error_type=%s.",
            state.get("analysis_id", "unknown"),
            type(exc).__name__,
        )
        return {
            "retrieved_evidence": [],
            "status": "FAILED",
            "error_message": (
                "Hybrid retrieval could not be initialized. Check dependencies "
                "and application settings."
            ),
        }

    retrieved: list[dict[str, Any]] = []
    failed_limitation_ids: set[str] = set()
    seen_pairs: set[tuple[str, str]] = set()
    target_patent_id = str(state.get("target_patent_id", ""))

    for limitation_index, limitation in enumerate(limitations, start=1):
        limitation_id = str(limitation.get("limitation_id", ""))
        query = str(limitation.get("text", "")).strip()
        if not limitation_id or not query:
            failed_limitation_ids.add(limitation_id or f"malformed-{limitation_index}")
            logger.warning(
                "Skipping malformed limitation in analysis_id=%s.",
                state.get("analysis_id", "unknown"),
            )
            continue

        try:
            candidates = retrieve_evidence(
                query=query,
                tenant_id=tenant_id,
                top_n=top_n,
            )
        except Exception as exc:
            failed_limitation_ids.add(limitation_id)
            # Avoid exception strings/tracebacks that could contain claim text.
            logger.error(
                "Evidence retrieval failed for analysis_id=%s limitation_id=%s "
                "error_type=%s.",
                state.get("analysis_id", "unknown"),
                limitation_id,
                type(exc).__name__,
            )
            continue

        for candidate in candidates:
            candidate_data = _model_to_dict(candidate)
            candidate_tenant_id = str(candidate_data.get("tenant_id", ""))
            if candidate_tenant_id != str(tenant_id):
                failed_limitation_ids.add(limitation_id)
                logger.error(
                    "Discarding cross-tenant retrieval candidate for analysis_id=%s.",
                    state.get("analysis_id", "unknown"),
                )
                continue

            # A patent must not be treated as prior art against itself.
            if (
                target_patent_id
                and str(candidate_data.get("patent_id", "")) == target_patent_id
            ):
                continue

            chunk_id = str(candidate_data.get("chunk_id", ""))
            if not chunk_id:
                continue
            unique_key = (limitation_id, chunk_id)
            if unique_key in seen_pairs:
                continue
            seen_pairs.add(unique_key)

            evidence_id = hashlib.sha256(
                f"{limitation_id}:{chunk_id}".encode("utf-8")
            ).hexdigest()[:32]
            retrieved.append(
                {
                    "limitation_id": limitation_id,
                    "evidence_id": evidence_id,
                    **candidate_data,
                }
            )

    if len(failed_limitation_ids) >= len(limitations):
        status = "FAILED"
        error_message = (
            "Evidence retrieval failed for all limitations; check the "
            "application logs."
        )
    elif failed_limitation_ids:
        status = "RETRIEVAL_PARTIAL"
        error_message = (
            f"Evidence retrieval failed or returned invalid tenant metadata for "
            f"{len(failed_limitation_ids)} limitation(s); assessments may be "
            "incomplete."
        )
    else:
        status = "RETRIEVED"
        error_message = None

    return {
        "retrieved_evidence": retrieved,
        "status": status,
        "error_message": error_message,
    }


def limitation_evaluator_node(state: AnalysisState) -> dict[str, Any]:
    """Assess each limitation against returned text using conservative rules.

    ``confidence`` is a lexical-evidence coverage heuristic, not the probability
    of infringement, novelty, validity, or legal equivalence. Contradiction is
    assigned only when the same excerpt explicitly negates the key terms; mere
    absence of a feature is never treated as contradictory evidence.
    """
    limitations = state.get("limitations", [])
    if not limitations:
        return {
            "assessments": [],
            "status": "FAILED",
            "error_message": state.get("error_message")
            or "No limitations are available for assessment.",
        }

    tenant_id = str(state.get("tenant_id", ""))
    retrieved_evidence = [
        item
        for item in state.get("retrieved_evidence", [])
        if str(item.get("tenant_id", "")) == tenant_id
    ]
    retrieval_failed = state.get("status") == "FAILED" and not retrieved_evidence
    assessments: list[dict[str, Any]] = []

    for limitation in limitations:
        limitation_id = str(limitation.get("limitation_id", ""))
        limitation_text = str(limitation.get("text", "")).strip()
        candidates = [
            item
            for item in retrieved_evidence
            if str(item.get("limitation_id", "")) == limitation_id
        ]

        retrieval_incomplete = state.get("status") in {
            "FAILED",
            "RETRIEVAL_PARTIAL",
        }
        if retrieval_failed or (retrieval_incomplete and not candidates):
            assessment = LimitationAssessmentResult(
                limitation_id=limitation_id,
                status="UNCERTAIN",
                explanation=(
                    "Evidence retrieval failed. No conclusion can be drawn "
                    "from the unavailable retrieval results."
                ),
                evidence=[],
                confidence=0.0,
            )
        else:
            assessment = _assess_limitation(limitation_id, limitation_text, candidates)
        assessments.append(assessment.model_dump(mode="json"))

    if state.get("status") == "FAILED" and not retrieved_evidence:
        final_status = "FAILED"
    elif state.get("error_message"):
        final_status = "COMPLETED_WITH_WARNINGS"
    else:
        final_status = "COMPLETED"

    return {
        "assessments": assessments,
        "status": final_status,
    }



def groundedness_guardrail_node(state: AnalysisState) -> dict[str, Any]:
    """Verify cited quotes against canonical tenant-owned TextChunk rows."""
    tenant_id = state.get("tenant_id", "")
    if not tenant_id:
        message = (
            "Groundedness verification skipped because tenant context is missing."
        )
        old_message = str(state.get("error_message") or "").strip()
        return {
            "assessments": _fail_closed_assessments(
                state.get("assessments", []),
                message=(
                    "Fail-Closed: Cited quote could not be verified against "
                    "source document text."
                ),
            ),
            "error_message": _append_messages(old_message, message),
            "status": "COMPLETED_WITH_WARNINGS",
        }

    try:
        from ai_engine.guardrails import GroundednessGuardrail

        assessments, warnings = GroundednessGuardrail.verify_assessments(
            state.get("assessments", []), tenant_id=tenant_id
        )
    except Exception as exc:
        # Guardrails must never convert an internal failure into a pass.
        logger.error(
            "Groundedness guardrail failed for analysis_id=%s error_type=%s.",
            state.get("analysis_id", "unknown"),
            type(exc).__name__,
        )
        warning = (
            "Fail-Closed: Cited quote could not be verified against source "
            "document text."
        )
        assessments = _fail_closed_assessments(
            state.get("assessments", []), message=warning
        )
        warnings = [warning]

    old_message = str(state.get("error_message") or "").strip()
    error_message = _append_messages(old_message, *warnings)
    result: dict[str, Any] = {"assessments": assessments}
    if warnings:
        result["error_message"] = error_message
        if state.get("status") != "FAILED":
            result["status"] = "COMPLETED_WITH_WARNINGS"
    return result


def scoring_node(state: AnalysisState) -> dict[str, Any]:
    """Calculate and attach review-queue screening metrics to graph state."""
    from ai_engine.scoring import MultiMetricScorer

    try:
        metrics = MultiMetricScorer.calculate_screening_priority(
            state.get("assessments", [])
        )
        return {"metrics": metrics}
    except Exception as exc:
        logger.error(
            "Screening scoring failed for analysis_id=%s error_type=%s.",
            state.get("analysis_id", "unknown"),
            type(exc).__name__,
        )
        message = (
            "Screening metrics could not be calculated. Check the application logs."
        )
        return {
            "metrics": {
                "retrieval_relevance": 0.0,
                "limitation_coverage": 0.0,
                "evidence_confidence": 0.0,
                "technical_correspondence": 0.0,
                "screening_priority_score": 0.0,
            },
            "error_message": _append_messages(
                str(state.get("error_message") or "").strip(), message
            ),
        }


def _fail_closed_assessments(
    assessments: list[dict[str, Any]],
    *,
    message: str,
) -> list[dict[str, Any]]:
    """Mark cited evidence unverified if guardrail initialization itself fails."""
    failed: list[dict[str, Any]] = []
    for original in assessments:
        assessment = dict(original)
        evidence_items = assessment.get("evidence", [])
        if isinstance(evidence_items, list):
            assessment["evidence"] = [
                {**item, "quote_verified": False}
                if isinstance(item, dict)
                else item
                for item in evidence_items
            ]
            if evidence_items:
                assessment["status"] = "UNCERTAIN"
                assessment["confidence"] = 0.0
                explanation = str(assessment.get("explanation", "")).strip()
                if message not in explanation:
                    assessment["explanation"] = f"{explanation}\n\n{message}".strip()
                assessment["quote_verified"] = False
        failed.append(assessment)
    return failed


def _append_messages(existing: str, *messages: str) -> str | None:
    """Append unique non-empty operational messages without replacing prior errors."""
    parts = [part.strip() for part in existing.splitlines() if part.strip()]
    for message in messages:
        cleaned = str(message).strip()
        if cleaned and cleaned not in parts:
            parts.append(cleaned)
    return "\n".join(parts) or None


def _candidate_relevance(candidate: dict[str, Any], fallback: float) -> float:
    """Choose a normalized rerank/dense signal, avoiding raw BM25 scores."""
    for key in ("rerank_score", "dense_score"):
        try:
            score = float(candidate.get(key, 0.0))
        except (TypeError, ValueError, OverflowError):
            continue
        if math.isfinite(score) and score > 0.0:
            return min(1.0, max(0.0, score))

    try:
        score = float(fallback)
    except (TypeError, ValueError, OverflowError):
        return 0.0
    return min(1.0, max(0.0, score)) if math.isfinite(score) else 0.0


def _split_claim_into_limitations(claim_text: str) -> list[str]:
    """Return conservative, ordered limitations from a claim string."""
    without_number = _LEADING_CLAIM_NUMBER_RE.sub("", claim_text, count=1).strip()
    if not without_number:
        return []

    explicit_parts = [
        part.strip(" \t\r\n,:")
        for part in _SPLIT_LIMITATION_RE.split(without_number)
        if part and part.strip(" \t\r\n,:")
    ]

    # Split only obvious component lists; avoid arbitrary comma/sentence splits.
    expanded: list[str] = []
    for part in explicit_parts:
        pieces = _LIST_ITEM_BOUNDARY_RE.split(part)
        for piece in pieces:
            cleaned = piece.strip(" \t\r\n,:")
            cleaned = _LEADING_CONJUNCTION_RE.sub("", cleaned).strip()
            if cleaned:
                expanded.append(cleaned)

    # If parsing boundaries caused no useful segmentation, retain the full claim.
    if not expanded:
        return [without_number]
    return _deduplicate_adjacent(expanded)


def _assess_limitation(
    limitation_id: str,
    limitation_text: str,
    candidates: list[dict[str, Any]],
) -> LimitationAssessmentResult:
    """Create a grounded assessment from ranked text candidates."""
    limitation_terms = _technical_terms(limitation_text)
    if not limitation_text or not limitation_terms:
        return LimitationAssessmentResult(
            limitation_id=limitation_id,
            status="UNCERTAIN",
            explanation=(
                "The limitation did not contain enough technical terms for "
                "the deterministic overlap evaluator. Manual review is required."
            ),
            evidence=[],
            confidence=0.0,
        )

    scored: list[tuple[float, float, dict[str, Any], str, set[str]]] = []
    for candidate in candidates:
        source_text = str(candidate.get("text", "")).strip()
        if not source_text:
            continue
        source_terms = _technical_terms(source_text)
        if not source_terms:
            continue
        shared_terms = limitation_terms & source_terms
        coverage = len(shared_terms) / len(limitation_terms)
        union_size = len(limitation_terms | source_terms)
        jaccard = len(shared_terms) / union_size if union_size else 0.0
        quote = _best_exact_quote(source_text, limitation_terms)
        score = min(1.0, max(0.0, 0.8 * coverage + 0.2 * jaccard))
        scored.append((score, coverage, candidate, quote, shared_terms))

    if not scored:
        return LimitationAssessmentResult(
            limitation_id=limitation_id,
            status="NOT_FOUND",
            explanation=(
                "The retriever returned no usable text for this limitation. "
                "This is not evidence that no relevant prior art exists."
            ),
            evidence=[],
            confidence=0.0,
        )

    scored.sort(
        key=lambda row: (
            row[0],
            float(row[2].get("rerank_score", 0.0) or 0.0),
            float(row[2].get("rrf_score", 0.0) or 0.0),
        ),
        reverse=True,
    )
    best_score, best_coverage, best_candidate, best_quote, shared_terms = scored[0]
    rerank_score = _safe_score(best_candidate.get("rerank_score", 0.0))
    source_text = str(best_candidate.get("text", ""))
    contradiction_quote = _explicit_negation_quote(
        source_text,
        limitation_terms,
    )
    explicit_contradiction = contradiction_quote is not None
    if explicit_contradiction and contradiction_quote:
        best_quote = contradiction_quote

    if explicit_contradiction:
        status = "CONTRADICTORY"
        explanation = (
            "A retrieved excerpt appears to explicitly negate one or more "
            "limitation terms. Check the full source context; this is a "
            "screening flag, not a legal conclusion."
        )
        confidence = min(0.65, max(0.2, best_coverage))
    elif best_coverage >= 0.80:
        status = "DIRECT_SUPPORT"
        explanation = (
            f"The strongest excerpt shares {len(shared_terms)} of "
            f"{len(limitation_terms)} normalized technical terms with the "
            "limitation. Review the quoted text and full source to verify that "
            "the technical relationship is actually disclosed."
        )
        confidence = best_score
    elif best_coverage >= 0.45:
        status = "PARTIAL_SUPPORT"
        explanation = (
            f"The strongest excerpt shares {len(shared_terms)} of "
            f"{len(limitation_terms)} normalized technical terms. The retrieved "
            "text may address only part of the limitation."
        )
        confidence = best_score
    elif best_coverage >= 0.25 and rerank_score >= 0.65:
        status = "POSSIBLE_EQUIVALENT"
        explanation = (
            "The reranker surfaced text with related terminology but direct "
            "textual overlap is limited. No legal equivalence is inferred; "
            "manual technical and legal review is required."
        )
        confidence = best_score
    else:
        status = "NOT_FOUND"
        explanation = (
            "The retrieved candidates did not provide sufficient textual "
            "overlap for this limitation. This does not establish the absence "
            "of relevant prior art outside the retrieved excerpts."
        )
        confidence = best_score

    evidence_items: list[EvidenceItem] = []
    if status in {
        "DIRECT_SUPPORT",
        "PARTIAL_SUPPORT",
        "POSSIBLE_EQUIVALENT",
        "CONTRADICTORY",
    }:
        for evidence_index, (_, coverage, candidate, quote, _) in enumerate(
            scored[:3]
        ):
            if evidence_index == 0 and explicit_contradiction and best_quote:
                quote = best_quote
            if not quote or coverage < 0.20:
                continue
            source_patent_id = str(candidate.get("patent_id", ""))
            source_version_id = str(candidate.get("document_version_id", ""))
            if not source_patent_id or not source_version_id:
                continue
            page_index = candidate.get("page_start")
            if page_index is None:
                page_index = candidate.get("page_end")
            evidence_items.append(
                EvidenceItem(
                    evidence_id=str(candidate.get("evidence_id", ""))
                    or _fallback_evidence_id(limitation_id, candidate),
                    source_patent_id=source_patent_id,
                    source_version_id=source_version_id,
                    exact_quote=quote,
                    page_index=_optional_int(page_index),
                    section_type=str(candidate.get("section_type", "UNKNOWN")),
                    chunk_id=str(candidate.get("chunk_id", "")) or None,
                    retrieval_score=_candidate_relevance(candidate, best_score),
                )
            )

    return LimitationAssessmentResult(
        limitation_id=limitation_id,
        status=status,
        explanation=explanation,
        evidence=evidence_items,
        confidence=min(1.0, max(0.0, confidence)),
        retrieval_relevance=_candidate_relevance(best_candidate, best_score),
        technical_correspondence=best_coverage,
    )


def _best_exact_quote(text: str, limitation_terms: set[str]) -> str:
    """Select the source sentence with highest term overlap verbatim."""
    matches = [match.group(0).strip() for match in _SENTENCE_RE.finditer(text)]
    matches = [match for match in matches if match]
    if not matches:
        return text.strip()

    def rank(sentence: str) -> tuple[float, int]:
        words = _technical_terms(sentence)
        return (
            len(words & limitation_terms) / max(1, len(limitation_terms)),
            len(sentence),
        )

    best = max(matches, key=rank)
    # The exact quote is always a substring of source retrieval text.
    return best.strip()


def _explicit_negation_quote(
    source_text: str,
    limitation_terms: set[str],
) -> str | None:
    """Return a verbatim sentence with explicit negation of key terms, if any."""
    if not limitation_terms:
        return None
    for sentence_match in _SENTENCE_RE.finditer(source_text):
        sentence = sentence_match.group(0).strip()
        if not _NEGATION_RE.search(sentence):
            continue
        shared = _technical_terms(sentence) & limitation_terms
        if len(shared) >= min(2, len(limitation_terms)):
            return sentence
    return None


def _technical_terms(text: str) -> set[str]:
    """Normalize technical terms without altering the source text."""
    return {
        token
        for token in _TOKEN_RE.findall(text.casefold())
        if token not in _STOPWORDS and len(token) > 1 and not token.isdigit()
    }


def _normalize_text(text: str) -> str:
    """Collapse whitespace and remove common leading claim-number syntax."""
    normalized = _WHITESPACE_RE.sub(" ", text).strip()
    return _LEADING_CLAIM_NUMBER_RE.sub("", normalized, count=1).strip()


def _deduplicate_adjacent(parts: Iterable[str]) -> list[str]:
    """Remove repeated neighboring segments while preserving order."""
    unique_parts: list[str] = []
    for part in parts:
        if not unique_parts or part.casefold() != unique_parts[-1].casefold():
            unique_parts.append(part)
    return unique_parts


def _model_to_dict(candidate: Any) -> dict[str, Any]:
    """Serialize Pydantic v2/v1 models and mapping-like candidate values."""
    model_dump = getattr(candidate, "model_dump", None)
    if callable(model_dump):
        result = model_dump(mode="json")
    else:
        legacy_dict = getattr(candidate, "dict", None)
        if callable(legacy_dict):
            result = legacy_dict()
        elif isinstance(candidate, dict):
            result = candidate.copy()
        else:
            raise TypeError("Retrieval candidate is not a supported mapping/model.")
    if not isinstance(result, dict):
        raise TypeError("Retrieval candidate serialization did not return a mapping.")
    return result


def _fallback_evidence_id(
    limitation_id: str,
    candidate: dict[str, Any],
) -> str:
    """Build a deterministic evidence identifier if the retrieval service lacks one."""
    identity = ":".join(
        (
            limitation_id,
            str(candidate.get("chunk_id", "")),
            str(candidate.get("document_version_id", "")),
        )
    )
    return uuid5(NAMESPACE_URL, f"patentshield:evidence:{identity}").hex


def _optional_int(value: Any) -> int | None:
    """Convert a source page index to an integer without inventing a page."""
    if value is None:
        return None
    try:
        page_index = int(value)
    except (TypeError, ValueError, OverflowError):
        return None
    return page_index if math.isfinite(page_index) and page_index >= 0 else None


def _safe_score(value: Any) -> float:
    """Return a finite score or zero for malformed candidate metadata."""
    try:
        score = float(value)
    except (TypeError, ValueError, OverflowError):
        return 0.0
    return min(1.0, max(0.0, score)) if math.isfinite(score) else 0.0
